CREATE TABLE NHIEM_VU_DU_AN (
    MANVDA INT IDENTITY(1,1) PRIMARY KEY,
    MADA INT,
    MANV VARCHAR(20),
    TENNHIEMVU NVARCHAR(255),
    MOTA NVARCHAR(MAX),
    NGAYBATDAU DATE,
    NGAYKETTHUC DATE,
    DOUUTIEN NVARCHAR(20),
    TRANGTHAI NVARCHAR(50),
    PHANTRAMHOANTHANH INT,
    GHICHUSAUHOANTHANH NVARCHAR(MAX),
    CREATEDAT DATETIME DEFAULT GETDATE(),
    CONSTRAINT FK_NHIEMVU_DUAN FOREIGN KEY (MADA) REFERENCES DU_AN(MADA) ON DELETE CASCADE,
    CONSTRAINT FK_NHIEMVU_PHANCONG FOREIGN KEY (MADA, MANV) REFERENCES PHANCONG_DU_AN(MaDA, MaNV) ON DELETE NO ACTION
);
GO

CREATE OR ALTER PROCEDURE sp_isEmployeeInProject
    @MADA INT,
    @MANV VARCHAR(20)
AS
BEGIN
    SELECT 1 FROM PHAN_CONG_DU_AN WHERE MADA = @MADA AND MANV = @MANV;
END;
GO

