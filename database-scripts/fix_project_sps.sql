CREATE OR ALTER PROCEDURE sp_updateProjectTask
    @MADA INT,
    @MANVDA INT,
    @MANV VARCHAR(20),
    @MANV_PASSED BIT,
    @TENNHIEMVU NVARCHAR(255),
    @TENNHIEMVU_PASSED BIT,
    @MOTA NVARCHAR(MAX),
    @MOTA_PASSED BIT,
    @NGAYBATDAU DATE,
    @NGAYBATDAU_PASSED BIT,
    @NGAYKETTHUC DATE,
    @NGAYKETTHUC_PASSED BIT,
    @DOUUTIEN NVARCHAR(20),
    @DOUUTIEN_PASSED BIT,
    @TRANGTHAI NVARCHAR(50),
    @TRANGTHAI_PASSED BIT,
    @PHANTRAMHOANTHANH INT,
    @PHANTRAMHOANTHANH_PASSED BIT,
    @GHICHUSAUHOANTHANH NVARCHAR(MAX),
    @GHICHUSAUHOANTHANH_PASSED BIT
AS
BEGIN
    UPDATE NHIEM_VU_DU_AN
    SET
        MANV = CASE WHEN @MANV_PASSED = 1 THEN @MANV ELSE MANV END,
        TENNHIEMVU = CASE WHEN @TENNHIEMVU_PASSED = 1 THEN @TENNHIEMVU ELSE TENNHIEMVU END,
        MOTA = CASE WHEN @MOTA_PASSED = 1 THEN @MOTA ELSE MOTA END,
        NGAYBATDAU = CASE WHEN @NGAYBATDAU_PASSED = 1 THEN @NGAYBATDAU ELSE NGAYBATDAU END,
        NGAYKETTHUC = CASE WHEN @NGAYKETTHUC_PASSED = 1 THEN @NGAYKETTHUC ELSE NGAYKETTHUC END,
        DOUUTIEN = CASE WHEN @DOUUTIEN_PASSED = 1 THEN @DOUUTIEN ELSE DOUUTIEN END,
        TRANGTHAI = CASE WHEN @TRANGTHAI_PASSED = 1 THEN @TRANGTHAI ELSE TRANGTHAI END,
        PHANTRAMHOANTHANH = CASE WHEN @PHANTRAMHOANTHANH_PASSED = 1 THEN @PHANTRAMHOANTHANH ELSE PHANTRAMHOANTHANH END,
        GHICHUSAUHOANTHANH = CASE WHEN @GHICHUSAUHOANTHANH_PASSED = 1 THEN @GHICHUSAUHOANTHANH ELSE GHICHUSAUHOANTHANH END
    OUTPUT INSERTED.*
    WHERE MADA = @MADA AND MANVDA = @MANVDA;
END;
GO

