CREATE OR ALTER PROCEDURE sp_getProjectMembers
    @MADA INT
AS
BEGIN
    SELECT pc.*, nv.TENNV, nv.EMAIL 
    FROM PHAN_CONG_DU_AN pc
    LEFT JOIN NHAN_VIEN nv ON pc.MANV = nv.MANV
    WHERE pc.MADA = @MADA;
END;
GO

CREATE OR ALTER PROCEDURE sp_getEmployeeProjects
    @MANV VARCHAR(20)
AS
BEGIN
    SELECT da.* 
    FROM DU_AN da
    INNER JOIN PHAN_CONG_DU_AN pc ON da.MADA = pc.MADA
    WHERE pc.MANV = @MANV;
END;
GO

CREATE OR ALTER PROCEDURE sp_getProjectsWithMembersByEmployee
    @MANV VARCHAR(20)
AS
BEGIN
    SELECT da.* 
    FROM DU_AN da
    INNER JOIN PHAN_CONG_DU_AN pc ON da.MADA = pc.MADA
    WHERE pc.MANV = @MANV;
END;
GO

