CREATE OR ALTER PROCEDURE sp_updateProject
    @MADA INT,
    @TENDA NVARCHAR(255),
    @TENDA_PASSED BIT,
    @MOTA NVARCHAR(MAX),
    @MOTA_PASSED BIT,
    @NGAYBATDAU DATE,
    @NGAYBATDAU_PASSED BIT,
    @NGAYKETTHUC DATE,
    @NGAYKETTHUC_PASSED BIT,
    @TRANGTHAI NVARCHAR(50),
    @TRANGTHAI_PASSED BIT
AS
BEGIN
    UPDATE DU_AN
    SET 
        TENDA = CASE WHEN @TENDA_PASSED = 1 THEN @TENDA ELSE TENDA END,
        MOTA = CASE WHEN @MOTA_PASSED = 1 THEN @MOTA ELSE MOTA END,
        NGAYBATDAU = CASE WHEN @NGAYBATDAU_PASSED = 1 THEN @NGAYBATDAU ELSE NGAYBATDAU END,
        NGAYKETTHUC = CASE WHEN @NGAYKETTHUC_PASSED = 1 THEN @NGAYKETTHUC ELSE NGAYKETTHUC END,
        TRANGTHAI = CASE WHEN @TRANGTHAI_PASSED = 1 THEN @TRANGTHAI ELSE TRANGTHAI END
    WHERE MADA = @MADA;
END;
GO

