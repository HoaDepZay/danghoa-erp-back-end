CREATE OR ALTER PROCEDURE sp_findDirectRoom
    @MANVA VARCHAR(20),
    @MANVB VARCHAR(20),
    @LOAIPHONG TINYINT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT p.*
    FROM PHONG_CHAT p
    INNER JOIN THANH_VIEN_PHONG_CHAT tv1 ON p.MAPHONG = tv1.MAPHONG AND tv1.MANV = @MANVA
    INNER JOIN THANH_VIEN_PHONG_CHAT tv2 ON p.MAPHONG = tv2.MAPHONG AND tv2.MANV = @MANVB
    WHERE p.LOAIPHONG = @LOAIPHONG
      AND (SELECT COUNT(*) FROM THANH_VIEN_PHONG_CHAT WHERE MAPHONG = p.MAPHONG) = 2;
END
GO

CREATE OR ALTER PROCEDURE sp_createDirectRoom
    @MANVA VARCHAR(20),
    @MANVB VARCHAR(20),
    @LOAIPHONG TINYINT,
    @MATHAMCHIEU VARCHAR(50)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @NewRoomId INT;
    
    INSERT INTO PHONG_CHAT (LOAIPHONG, MATHAMCHIEU)
    VALUES (@LOAIPHONG, @MATHAMCHIEU);
    
    SET @NewRoomId = SCOPE_IDENTITY();
    
    INSERT INTO THANH_VIEN_PHONG_CHAT (MAPHONG, MANV, VAITRO)
    VALUES 
        (@NewRoomId, @MANVA, N'Thành viên'),
        (@NewRoomId, @MANVB, N'Thành viên');
        
    SELECT * FROM PHONG_CHAT WHERE MAPHONG = @NewRoomId;
END
GO

CREATE OR ALTER PROCEDURE sp_getOrCreateReferenceRoom
    @LOAIPHONG TINYINT,
    @MATHAMCHIEU VARCHAR(50),
    @TENPHONG NVARCHAR(255) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @RoomId INT;
    
    SELECT @RoomId = MAPHONG FROM PHONG_CHAT 
    WHERE LOAIPHONG = @LOAIPHONG AND MATHAMCHIEU = @MATHAMCHIEU;
    
    IF @RoomId IS NULL
    BEGIN
        INSERT INTO PHONG_CHAT (LOAIPHONG, MATHAMCHIEU, TENPHONG)
        VALUES (@LOAIPHONG, @MATHAMCHIEU, @TENPHONG);
        
        SET @RoomId = SCOPE_IDENTITY();
    END
    
    SELECT * FROM PHONG_CHAT WHERE MAPHONG = @RoomId;
END
GO

