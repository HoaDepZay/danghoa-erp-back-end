CREATE OR ALTER PROCEDURE sp_createCustomGroupRoom
    @CREATORMANV VARCHAR(20),
    @TENPHONG NVARCHAR(255),
    @MATHAMCHIEU VARCHAR(50),
    @MEMBERIDS NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @NewRoomId INT;
    
    INSERT INTO PHONG_CHAT (LOAIPHONG, MATHAMCHIEU, TENPHONG)
    VALUES (4, @MATHAMCHIEU, @TENPHONG); -- LOAIPHONG = 4 (GROUP)
    
    SET @NewRoomId = SCOPE_IDENTITY();
    
    -- Insert members from comma separated string
    INSERT INTO THANH_VIEN_PHONG_CHAT (MAPHONG, MANV, VAITRO)
    SELECT DISTINCT @NewRoomId, LTRIM(RTRIM(value)), N'Thành viên'
    FROM STRING_SPLIT(@MEMBERIDS, ',');
    
    -- Ensure creator is in the room as admin
    IF NOT EXISTS (SELECT 1 FROM THANH_VIEN_PHONG_CHAT WHERE MAPHONG = @NewRoomId AND MANV = @CREATORMANV)
    BEGIN
        INSERT INTO THANH_VIEN_PHONG_CHAT (MAPHONG, MANV, VAITRO)
        VALUES (@NewRoomId, @CREATORMANV, N'Quản trị viên');
    END
    ELSE
    BEGIN
        UPDATE THANH_VIEN_PHONG_CHAT
        SET VAITRO = N'Quản trị viên'
        WHERE MAPHONG = @NewRoomId AND MANV = @CREATORMANV;
    END

    SELECT * FROM PHONG_CHAT WHERE MAPHONG = @NewRoomId;
END
GO

