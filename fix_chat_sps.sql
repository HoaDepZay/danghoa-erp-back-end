GO

-- Stored Procedures

CREATE OR ALTER PROCEDURE sp_getMyRooms
    @MaNV VARCHAR(20)
AS
BEGIN
    SET NOCOUNT ON;
    
    SELECT 
        p.MAPHONG,
        p.TENPHONG,
        p.LOAIPHONG,
        p.MATHAMCHIEU,
        p.NGAYTAO,
        (SELECT COUNT(*) FROM THANH_VIEN_PHONG_CHAT tv2 WHERE tv2.MAPHONG = p.MAPHONG) AS SoThanhVien,
        (SELECT TOP 1 NOIDUNG FROM TIN_NHAN tn WHERE tn.MAPHONG = p.MAPHONG ORDER BY THOIGIANGUI DESC) AS TinNhanGanNhat
    FROM PHONG_CHAT p
    INNER JOIN THANH_VIEN_PHONG_CHAT tv ON p.MAPHONG = tv.MAPHONG
    WHERE tv.MANV = @MaNV
    ORDER BY (SELECT TOP 1 THOIGIANGUI FROM TIN_NHAN tn WHERE tn.MAPHONG = p.MAPHONG ORDER BY THOIGIANGUI DESC) DESC;
END
GO

