CREATE OR ALTER PROCEDURE sp_getRoomMessages
    @MaPhong INT,
    @Limit INT = 50
AS
BEGIN
    SET NOCOUNT ON;
    -- Note: Assuming table NHANVIEN has columns MANV and TENNV
    SELECT TOP (@Limit)
        tn.MATN,
        tn.MAPHONG,
        tn.MANV_GUI,
        nv.TENNV AS TenNguoiGui,
        tn.NOIDUNG,
        tn.THOIGIANGUI
    FROM TIN_NHAN tn
    LEFT JOIN NHANVIEN nv ON tn.MANV_GUI = nv.MANV
    WHERE tn.MAPHONG = @MaPhong
    ORDER BY tn.THOIGIANGUI DESC;
END
GO

CREATE OR ALTER PROCEDURE sp_getLatestMessageByRoom
    @MAPHONG INT
AS
BEGIN
    SET NOCOUNT ON;
    SELECT TOP 1 MATN, MAPHONG, MANV_GUI, NOIDUNG, THOIGIANGUI
    FROM TIN_NHAN
    WHERE MAPHONG = @MAPHONG
    ORDER BY THOIGIANGUI DESC;
END
GO

CREATE OR ALTER PROCEDURE sp_searchMessagesByKeyword
    @MAPHONG INT,
    @TUKHOA NVARCHAR(MAX)
AS
BEGIN
    SET NOCOUNT ON;
    SELECT MATN, MAPHONG, MANV_GUI, NOIDUNG, THOIGIANGUI
    FROM TIN_NHAN
    WHERE MAPHONG = @MAPHONG AND NOIDUNG LIKE N'%' + @TUKHOA + N'%'
    ORDER BY THOIGIANGUI DESC;
END
GO

CREATE OR ALTER PROCEDURE sp_sendMessage
    @MaPhong INT,
    @MaNV_Gui VARCHAR(20),
    @NoiDung NVARCHAR(MAX),
    @FileUrl NVARCHAR(MAX) = NULL,
    @FileType VARCHAR(50) = NULL
AS
BEGIN
    SET NOCOUNT ON;
    DECLARE @Inserted TABLE (
        MATN INT, MAPHONG INT, MANV_GUI VARCHAR(20), 
        NOIDUNG NVARCHAR(MAX), THOIGIANGUI DATETIME, 
        FILEURL NVARCHAR(MAX), FILETYPE VARCHAR(50)
    );

    INSERT INTO TIN_NHAN (MAPHONG, MANV_GUI, NOIDUNG, FILEURL, FILETYPE)
    OUTPUT INSERTED.MATN, INSERTED.MAPHONG, INSERTED.MANV_GUI, INSERTED.NOIDUNG, INSERTED.THOIGIANGUI, INSERTED.FILEURL, INSERTED.FILETYPE
    INTO @Inserted
    VALUES (@MaPhong, @MaNV_Gui, @NoiDung, @FileUrl, @FileType);

    SELECT * FROM @Inserted;
END
GO

